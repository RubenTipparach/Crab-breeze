// Writes the arms lab's melee moves and gun recoil (tools/mockups/mech_melee.js, the one source) to the game's data,
// data/combat/melee_moves.ron, read by cb_core::mech::melee_moves (openspec change `close-combat` task 2.4). Moves the
// owner saved on the lab page come back through the page's database; pass them as a JSON file to export those instead
// of the defaults:
//   node tools/mockups/export_melee_moves.mjs [saved.json]
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "..");
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "tools/mockups/mech_melee.js"), "utf8") + "\nthis.M = MELEE_MOVES; this.O = MELEE_ORDER;", ctx);
const moves = ctx.M;
if (process.argv[2]) Object.assign(moves, JSON.parse(fs.readFileSync(process.argv[2], "utf8")));
const n = v => { const x = Number(v || 0); return Number.isInteger(x) ? x.toFixed(1) : String(+x.toFixed(4)); };
let out = "// Generated by tools/mockups/export_melee_moves.mjs from the arms lab's moves (tools/mockups/mech_melee.js): edit\n" +
  "// the moves there, or on the Mech Arms Lab page, and export again. Each key: seconds in, and per bone an offset over the\n" +
  "// pose beneath as (rx, ry, rz) radians in the bone's own axes and (px, py, pz) metres in its parent's; `crouch` folds\n" +
  "// the legs (as the boarding kneel's amount). `hit_s` is when the blow lands; `stance` how much of a struck mech's stance\n" +
  "// it breaks, in blows; `fire` marks a gun's recoil.\n(\n    moves: {\n";
for (const id of ctx.O) {
  const m = moves[id];
  out += `        "${id}": (\n            arm: "${m.arm}",\n            hit_s: ${n(m.hit_s)},\n            stance: ${n(m.stance || 1)},\n            fire: ${!!m.fire},\n            keys: [\n`;
  for (const k of m.keys) {
    const bones = Object.entries(k.b || {});
    let line = `                (t_s: ${n(k.t)}`;
    if (bones.length) line += ", bones: {" + bones.map(([b, v]) => `"${b}": (${[0, 1, 2, 3, 4, 5].map(i => n(v[i])).join(", ")})`).join(", ") + "}";
    if (k.crouch) line += `, crouch: ${n(k.crouch)}`;
    out += line + "),\n";
  }
  out += "            ],\n        ),\n";
}
out += "    },\n)\n";
fs.writeFileSync(path.join(root, "data/combat/melee_moves.ron"), out);
console.log(`wrote data/combat/melee_moves.ron: ${ctx.O.length} moves`);
